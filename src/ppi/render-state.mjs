export function advanceD3DContext(
  context,
  {
    drawType = 0,
    blendMode = 0,
    force = false,
    renderStates = [],
    samplerStates = [],
    onCall,
  } = {},
) {
  const mode = PARTICLE_BLEND_FACTORS[blendMode] ? blendMode : 0;
  const call = (kind, stage, state, value) => {
    value >>>= 0;
    if (kind === 1) context.states.set(state, value);
    else if (kind === 3) context.samplers.set(state, value);
    else {
      if (!context.stages.has(stage)) context.stages.set(stage, new Map());
      context.stages.get(stage).set(state, value);
    }
    onCall?.([kind, stage, state, value]);
  };
  if (context.lastBlend !== blendMode || force) {
    const blend = PARTICLE_BLEND_FACTORS[mode];
    call(1, 0, 19, blend.d3dSource);
    call(1, 0, 20, blend.d3dDestination);
    context.lastBlend = blendMode;
  }
  if (context.lastDrawType === 7 || context.lastDrawType !== drawType || force) {
    for (const [kind, stage, state, original] of profiles[
      Number(Boolean(context.depthStencilEnabled))
    ][drawType] || []) {
      let value = original;
      if (kind === 3 && drawType !== 6 && state === 5) value = context.magFilter;
      if (kind === 3 && drawType !== 6 && state === 6) value = context.minFilter;
      if (kind === 1 && ![0, 6].includes(drawType) && state === 161)
        value = context.multisampleAntialias;
      call(kind, stage, state, value);
    }
    context.lastDrawType = drawType;
  }
  for (const [state, value] of renderStates) call(1, 0, state, value);
  for (const [state, value] of samplerStates) call(3, 0, state, value);
  return context;
}
