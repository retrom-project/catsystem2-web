export function particleNativeContract(version, id) {
  const count = version === 0x20000 ? 51 : 44;
  if (!Number.isInteger(id) || id < 0 || id >= count)
    throw new RangeError(`Unknown PTCL native ${id} for version ${version.toString(16)}`);
  return PTCL_NATIVE_CONTRACTS[id];
}
